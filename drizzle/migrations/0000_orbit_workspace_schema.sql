-- Roles live in their own table (never on profiles).
create table public.user_roles (
  id uuid primary key default gen_random_uuid(),
  user_id uuid references auth.users(id) on delete cascade not null,
  role public.app_role not null,
  created_at timestamptz not null default now(),
  unique (user_id, role)
);
grant select on public.user_roles to authenticated;
grant all on public.user_roles to service_role;
alter table public.user_roles enable row level security;

-- Imported users keep their original role here until they verify their email. Server-only.
create table public.pending_user_roles (
  profile_id bigint not null references public.profiles(id) on delete cascade,
  role public.app_role not null,
  primary key (profile_id, role)
);
grant all on public.pending_user_roles to service_role;
alter table public.pending_user_roles enable row level security;

create or replace function public.has_role(_user_id uuid, _role public.app_role)
returns boolean language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.user_roles where user_id = _user_id and role = _role)
$$;

create or replace function public.is_workspace_member(_user_id uuid)
returns boolean language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.user_roles r where r.user_id = _user_id)
     and not exists (
       select 1 from public.profiles p
       where p.auth_user_id = _user_id and coalesce(p.status, 'active') in ('suspended', 'inactive')
     )
$$;

create policy "Users read own roles" on public.user_roles for select to authenticated
  using (user_id = auth.uid() or public.has_role(auth.uid(), 'admin'));

