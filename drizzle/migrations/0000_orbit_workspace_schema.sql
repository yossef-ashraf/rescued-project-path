alter table public.profiles enable row level security;
create policy "Members read profiles" on public.profiles for select to authenticated
  using (public.is_workspace_member(auth.uid()) or auth_user_id = auth.uid());
create policy "Admins insert profiles" on public.profiles for insert to authenticated
  with check (public.has_role(auth.uid(), 'admin'));
create policy "Admins or owner update profiles" on public.profiles for update to authenticated
  using (public.has_role(auth.uid(), 'admin') or auth_user_id = auth.uid())
  with check (public.has_role(auth.uid(), 'admin') or auth_user_id = auth.uid());
create policy "Admins delete profiles" on public.profiles for delete to authenticated
  using (public.has_role(auth.uid(), 'admin'));

-- Workspace tables: every signed-in workspace member shares the same data (as in the original app).
do $$
declare t text;
begin
  foreach t in array array[
    'setting_settings','finance_fiscal_months','finance_debts','finance_credits','finance_investments_and_savings',
    'finance_transactions','finance_market_prices','op_tasks','op_todo_items','local_projects','leads','courses',
    'setting_notifications','setting_vault_passwords','material_knowledge_library','learning_lesson_comments',
    'material_categories','op_task_comments','op_task_attachments','lead_comments','lead_attachments',
    'profile_personal_info','profile_about','profile_education','profile_certificates','profile_experience',
    'profile_projects','profile_skills','profile_pages_sections','job_runs','job_locks','setting_shared_links',
    'setting_shared_link_views','learning_lessons','learning_lesson_attachments','learning_lesson_resources'
  ] loop
    execute format('grant select, insert, update, delete on public.%I to authenticated', t);
    execute format('grant all on public.%I to service_role', t);
    execute format('alter table public.%I enable row level security', t);
    execute format('create policy "Members manage %s" on public.%I for all to authenticated using (public.is_workspace_member(auth.uid())) with check (public.is_workspace_member(auth.uid()))', t, t);
  end loop;
  foreach t in array array['setting_auth_logs','setting_auth_otps'] loop
    execute format('grant select, insert, update, delete on public.%I to authenticated', t);
    execute format('grant all on public.%I to service_role', t);
    execute format('alter table public.%I enable row level security', t);
    execute format('create policy "Admins read %s" on public.%I for select to authenticated using (public.has_role(auth.uid(), ''admin''))', t, t);
    execute format('create policy "Admins delete %s" on public.%I for delete to authenticated using (public.has_role(auth.uid(), ''admin''))', t, t);
    execute format('create policy "Members write %s" on public.%I for insert to authenticated with check (public.is_workspace_member(auth.uid()))', t, t);
  end loop;
end $$;

-- Account linking: runs once an email is verified (or an account is created already confirmed).
-- Imported users are matched by verified email to their original profile and get their original role back.
-- The very first verified account becomes the workspace admin; everyone else waits for an admin to grant access.
create or replace function public.handle_auth_user_verified()
returns trigger language plpgsql security definer set search_path = public as $$
declare
  v_profile_id bigint;
  v_base text;
  v_username text;
  v_n int := 0;
begin
  if new.email_confirmed_at is null then return new; end if;
  if tg_op = 'UPDATE' and old.email_confirmed_at is not null then return new; end if;
  if exists (select 1 from public.profiles where auth_user_id = new.id) then return new; end if;

  select id into v_profile_id from public.profiles
   where lower(email) = lower(new.email) and auth_user_id is null
   order by id limit 1;

  if v_profile_id is not null then
    update public.profiles set auth_user_id = new.id, updated_at = now() where id = v_profile_id;
    insert into public.user_roles (user_id, role)
      select new.id, role from public.pending_user_roles where profile_id = v_profile_id
      on conflict do nothing;
    delete from public.pending_user_roles where profile_id = v_profile_id;
  else
    v_base := regexp_replace(lower(split_part(new.email, '@', 1)), '[^a-z0-9_.-]', '', 'g');
    if v_base = '' then v_base := 'user'; end if;
    v_username := v_base;
    while exists (select 1 from public.profiles where lower(username) = v_username) loop
      v_n := v_n + 1;
      v_username := v_base || v_n::text;
    end loop;
    insert into public.profiles (name, email, username, status, auth_user_id, created_at, updated_at)
    values (coalesce(nullif(new.raw_user_meta_data->>'name', ''), nullif(new.raw_user_meta_data->>'full_name', ''), v_base),
            new.email, v_username, 'active', new.id, now(), now());
  end if;

  if not exists (select 1 from public.user_roles where role = 'admin') then
    insert into public.user_roles (user_id, role) values (new.id, 'admin') on conflict do nothing;
  end if;
  return new;
end;
$$;

create trigger on_auth_user_created_verified
  after insert on auth.users
  for each row execute function public.handle_auth_user_verified();
create trigger on_auth_user_email_verified
  after update of email_confirmed_at on auth.users
  for each row execute function public.handle_auth_user_verified();

-- Non-admins may edit their own profile details but never their status, email, or account link.
create or replace function public.guard_profile_self_update()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  if auth.uid() is null or public.has_role(auth.uid(), 'admin') then return new; end if;
  new.status := old.status;
  new.email := old.email;
  new.auth_user_id := old.auth_user_id;
  return new;
end;
$$;
create trigger guard_profile_self_update before update on public.profiles
  for each row execute function public.guard_profile_self_update();